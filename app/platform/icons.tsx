// Icon system
//
// The app had no icon library — navigation used assorted geometric glyphs
// (◈ ◍ ◎ ⬡ ◉ ▦ ✎ ⌂ ⚙) mixed with emoji (🔔 📄 🗑 🖼), which is exactly the
// "mixed icon families" the design brief rules out. Rather than add a
// runtime dependency for ~20 glyphs, this is a small hand-drawn set in
// Lucide's geometry and conventions: 24x24 viewBox, no fill, currentColor
// stroke, 1.75 stroke-width, round caps and joins. One family, one weight,
// one sizing rule.
//
// Every icon is decorative here: navigation items always render a real text
// label beside them, and the collapsed sidebar supplies an accessible name
// via aria-label on the button itself. So each <svg> is aria-hidden and the
// button, not the icon, carries the name.
// ---------------------------------------------------------------------------

